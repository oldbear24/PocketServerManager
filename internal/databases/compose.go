package databases

import (
	"fmt"
	"slices"
	"strings"

	"go.yaml.in/yaml/v4"
)

// ServerService is the Compose service of a shared server's database container.
const ServerService = "db"

// ServerEnvKey is the variable of a shared server's env file that holds its
// administrator's password, as a reference the panel resolves on delivery.
const ServerEnvKey = "PC_ADMIN_PASSWORD"

// Server describes a shared server to generate the Compose file of.
type Server struct {
	Name           string
	Engine         Engine
	Image          string
	Volume         string
	MaxConnections int
	// Buffer is the cache memory, see BufferSize.
	Buffer uint64
}

// VolumeName is the named volume with a shared server's data.
func VolumeName(server string) string {
	return "pcdb-" + server + "-data"
}

// ServerCompose generates the Compose file of a shared server: the official image,
// a named volume, a health check, and no published ports. It joins the networks of
// the applications through the override of each deploy, not through this file.
func ServerCompose(s Server) string {
	var engineLines string
	switch s.Engine.Name {
	case MariaDB.Name:
		engineLines = fmt.Sprintf(`    command:
      - --innodb-buffer-pool-size=%s
      - --max-connections=%d
    environment:
      MARIADB_ROOT_PASSWORD: ${%s}
      # minor upgrades bring their schema changes with them
      MARIADB_AUTO_UPGRADE: "1"
    healthcheck:
      test: ["CMD", "healthcheck.sh", "--connect", "--innodb_initialized"]
`, megabytes(s.Buffer), s.MaxConnections, ServerEnvKey)
	default:
		engineLines = fmt.Sprintf(`    command:
      - postgres
      - -c
      - shared_buffers=%sB
      - -c
      - max_connections=%d
    environment:
      POSTGRES_PASSWORD: ${%s}
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U postgres -d postgres"]
`, megabytes(s.Buffer), s.MaxConnections, ServerEnvKey)
	}

	return fmt.Sprintf(`# The shared %[2]s server %[1]s, generated by PocketCloud. Applications reach
# it as %[1]s:%[3]d on networks of their own; it publishes no ports.
services:
  %[4]s:
    image: %[5]s
    restart: unless-stopped
%[6]s      interval: 10s
      timeout: 5s
      retries: 5
      start_period: 60s
    volumes:
      - data:%[7]s
    labels:
      pocketcloud.role: db
      pocketcloud.db.server: %[1]s

volumes:
  data:
    name: %[8]s
`, s.Name, s.Engine.Label, s.Engine.Port, ServerService, s.Image, engineLines, s.Engine.DataDir, s.Volume)
}

// ServerEnv is the env file of a shared server.
func ServerEnv(server string) string {
	return ServerEnvKey + "=${secret:" + AdminSecretName(server) + "}\n"
}

// Override generates the second Compose file of a deploy, which puts services on
// database networks. Without aliases every service of the stack joins every
// network: the applications. With aliases only the given service joins, under
// them: a shared server, which the applications find by its name.
//
// A service whose file names no networks is on the default network only; naming
// one in an override would take it off that one, so the override names it too.
// Services with a network_mode of their own cannot join networks and are left out.
func Override(compose string, networks []string, service string, aliases []string) (string, error) {
	if len(networks) == 0 {
		return "", nil
	}

	var file struct {
		Services map[string]struct {
			Networks    any    `yaml:"networks"`
			NetworkMode string `yaml:"network_mode"`
		} `yaml:"services"`
	}
	if err := yaml.Unmarshal([]byte(compose), &file); err != nil {
		return "", fmt.Errorf("the Compose file cannot be read: %w", err)
	}

	names := []string{}
	for name := range file.Services {
		if service == "" || name == service {
			names = append(names, name)
		}
	}
	slices.Sort(names)

	type endpoint struct {
		Aliases []string `yaml:"aliases,omitempty"`
	}
	type overrideService struct {
		Networks map[string]endpoint `yaml:"networks"`
	}
	type externalNetwork struct {
		External bool `yaml:"external"`
	}

	out := struct {
		Services map[string]overrideService `yaml:"services"`
		Networks map[string]externalNetwork `yaml:"networks"`
	}{
		Services: map[string]overrideService{},
		Networks: map[string]externalNetwork{},
	}

	for _, name := range names {
		definition := file.Services[name]
		if definition.NetworkMode != "" {
			continue
		}

		joined := map[string]endpoint{}
		if definition.Networks == nil {
			joined["default"] = endpoint{}
		}
		for _, network := range networks {
			joined[network] = endpoint{Aliases: aliases}
		}
		out.Services[name] = overrideService{Networks: joined}
	}

	if len(out.Services) == 0 {
		return "", nil
	}

	for _, network := range networks {
		out.Networks[network] = externalNetwork{External: true}
	}

	raw, err := yaml.Marshal(out)
	if err != nil {
		return "", err
	}

	return "# Generated by PocketCloud for every deploy: the database networks of this stack.\n" +
		strings.TrimLeft(string(raw), "\n"), nil
}
